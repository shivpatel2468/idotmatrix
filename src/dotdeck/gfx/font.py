"""1-bit bitmap fonts. Every lit pixel is 100 % on; no antialiasing, ever.

Three families form the type scale (see docs/DISPLAY_DESIGN.md):

========  ======  ==========================================================
font      height  use
========  ======  ==========================================================
tiny      5 px    labels, units, secondary data, scrolling lines (8 chars/row)
small     7 px    primary values, titles (5-6 chars/row)
big       10 px   hero numerals (clock, timers, prices). Digits and ':' only
========  ======  ==========================================================

Glyphs are proportional. Lower-case input is upper-cased for tiny and small.
Digits share one width within a family, so changing numbers never jitter.
"""

from __future__ import annotations

from dataclasses import dataclass
from typing import TYPE_CHECKING

import numpy as np

if TYPE_CHECKING:
    from .color import RGB
    from .frame import Frame


@dataclass(frozen=True)
class Font:
    name: str
    height: int
    glyphs: dict[str, np.ndarray]  # bool (height, width)
    fallback: str
    upper: bool

    def glyph(self, ch: str) -> np.ndarray:
        if self.upper:
            ch = ch.upper()
        g = self.glyphs.get(ch)
        if g is None:
            g = self.glyphs[self.fallback]
        return g


def _compile(name: str, height: int, raw: dict[str, list[str]], fallback: str, upper: bool) -> Font:
    glyphs: dict[str, np.ndarray] = {}
    for ch, rows in raw.items():
        if len(rows) != height:
            raise ValueError(f"font {name}: glyph {ch!r} has {len(rows)} rows, want {height}")
        w = len(rows[0])
        if any(len(r) != w for r in rows):
            raise ValueError(f"font {name}: glyph {ch!r} rows have uneven width")
        glyphs[ch] = np.array([[c == "#" for c in r] for r in rows], dtype=bool)
    return Font(name, height, glyphs, fallback, upper)


