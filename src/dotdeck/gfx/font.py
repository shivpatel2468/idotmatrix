FONTS: dict[str, Font] = {
    "tiny": _compile("tiny", 5, _TINY, "?", upper=True),
    "small": _compile("small", 7, _SMALL, "?", upper=True),
    "big": _compile("big", 10, _BIG, " ", upper=False),
}


def get_font(name: str) -> Font:
    try:
        return FONTS[name]
    except KeyError:
        raise ValueError(f"unknown font {name!r}; choose from {sorted(FONTS)}") from None


def measure(text: str, font: str = "tiny", spacing: int = 1) -> int:
    """Pixel width of `text` (no trailing spacing)."""
    if not text:
        return 0
    f = get_font(font)
    return sum(f.glyph(ch).shape[1] for ch in text) + spacing * (len(text) - 1)


def draw_text(
    frame: Frame,
    x: int,
    y: int,
    text: str,
    color: RGB,
    font: str = "tiny",
    clip: tuple[int, int, int, int] | None = None,
    spacing: int = 1,
) -> int:
    f = get_font(font)
    cx0, cy0, cx1, cy1 = clip if clip is not None else (0, 0, 31, 31)
    cx0, cy0 = max(0, cx0), max(0, cy0)
    cx1, cy1 = min(31, cx1), min(31, cy1)
    px = frame.px
    cur = x
    for ch in text:
        g = f.glyph(ch)
        gh, gw = g.shape
        if cur > cx1:
            break
        if cur + gw - 1 >= cx0:
            # intersect glyph box with clip box
            x0, x1 = max(cur, cx0), min(cur + gw - 1, cx1)
            y0, y1 = max(y, cy0), min(y + gh - 1, cy1)
            if x0 <= x1 and y0 <= y1:
                sub = g[y0 - y : y1 - y + 1, x0 - cur : x1 - cur + 1]
                px[y0 : y1 + 1, x0 : x1 + 1][sub] = color
        cur += gw + spacing
    return cur - spacing


def wrap(text: str, width: int = 32, font: str = "tiny") -> list[str]:
    """Greedy word wrap to `width` pixels; words longer than a line are hard-split."""
    words = text.split()
    lines: list[str] = []
    line = ""
    for word in words:
        cand = f"{line} {word}" if line else word
        if measure(cand, font) <= width:
            line = cand
            continue
        if line:
            lines.append(line)
        while measure(word, font) > width:
            cut = len(word)
            while cut > 1 and measure(word[:cut], font) > width:
                cut -= 1
            lines.append(word[:cut])
            word = word[cut:]
        line = word
    if line:
        lines.append(line)
    return lines


def fit(text: str, width: int, font: str = "tiny") -> str:
    """Truncate with an ellipsis so the text fits in `width` pixels."""
    if measure(text, font) <= width:
        return text
    ell = "…" if "…" in get_font(font).glyphs else "."
    while text and measure(text + ell, font) > width:
        text = text[:-1]
    return text + ell


def marquee_x(
    text: str,
    t: float,
    box_x: int,
    box_w: int,
    font: str = "tiny",
    speed: float = 12.0,
    gap: int = 12,
    hold: float = 1.2,
) -> int:
    """x position for a scrolling line that pauses at the start of each pass.

    Returns a fixed, left-aligned x when the text already fits.
    """
    w = measure(text, font)
    if w <= box_w:
        return box_x + (box_w - w) // 2
    travel = w + gap
    period = hold + travel / speed
    phase = t % period
    if phase < hold:
        return box_x
    return box_x - int((phase - hold) * speed)


def draw_marquee(
    frame: Frame,
    text: str,
    t: float,
    x: int,
    y: int,
    w: int,
    color: RGB,
    font: str = "tiny",
    speed: float = 12.0,
    gap: int = 12,
    hold: float = 1.2,
) -> None:
    """Draw `text` inside the box [x, x+w) — centred if it fits, otherwise a seamless loop."""
    from .color import to_rgb

    color = to_rgb(color)
    f = get_font(font)
    clip = (x, y, x + w - 1, y + f.height - 1)
    tw = measure(text, font)
    sx = marquee_x(text, t, x, w, font, speed, gap, hold)
    draw_text(frame, sx, y, text, color, font, clip)
    if tw > w:
        draw_text(frame, sx + tw + gap, y, text, color, font, clip)
