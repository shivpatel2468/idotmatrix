@lru_cache(maxsize=8)
def land(w: int = 32, h: int = 16) -> np.ndarray:
    """Boolean (h, w) array, True where there is land. `(w, h)` must be one of SIZES."""
    rows = _MASKS[(w, h)]
    return np.array([[c == "#" for c in r] for r in rows], dtype=bool)


def project(lat: float, lon: float, w: int = 32, h: int = 16) -> tuple[float, float]:
    """Equirectangular (lat, lon) -> fractional pixel (x, y) on a w×h world map."""
    lon = (lon + 180.0) % 360.0 - 180.0
    return (lon + 180.0) / 360.0 * w, (90.0 - max(-90.0, min(90.0, lat))) / 180.0 * h


def draw_world(
    f: Frame,
    land_color: ColorLike,
    sea_color: ColorLike | None = (0, 0, 0),
    *,
    size: tuple[int, int] = (32, 16),
    x: int = 0,
    y: int = 0,
    center_lon: float = 0.0,
    view: tuple[int, int] | None = None,
    offset: tuple[int, int] = (0, 0),
) -> None:
    """Draw a world map with its top-left at (x, y).

    `center_lon` rolls the map horizontally (wraps around the date line). `view=(vw, vh)` with `offset=(ox, oy)`
    shows only a window of a bigger map (e.g. a 32×32 window of the 128×64 map around your location).
    Clipped to the panel like every Frame primitive.
    """
    w, h = size
    m = land(w, h)
    shift = round(center_lon / 360.0 * w)
    if shift:
        m = np.roll(m, -shift, axis=1)
    ox, oy = offset
    vw, vh = view or (w, h)
    sub = np.zeros((vh, vw), dtype=bool)
    for j in range(vh):
        sy = oy + j
        if 0 <= sy < h:
            sub[j] = m[sy, [(ox + i) % w for i in range(vw)]]
    lc = np.array(to_rgb(land_color), dtype=np.uint8)
    sc = None if sea_color is None else np.array(to_rgb(sea_color), dtype=np.uint8)
    x0, y0 = max(0, x), max(0, y)
    x1, y1 = min(32, x + vw), min(32, y + vh)
    if x1 <= x0 or y1 <= y0:
        return
    region = sub[y0 - y : y1 - y, x0 - x : x1 - x]
    tgt = f.px[y0:y1, x0:x1]
    tgt[region] = lc
    if sc is not None:
        tgt[~region] = sc
