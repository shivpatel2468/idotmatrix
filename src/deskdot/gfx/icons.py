def icon_sprite(name: str, color: ColorLike) -> Sprite | None:
    rows = ICONS.get(name)
    return Sprite.parse(rows, {"#": to_rgb(color)}) if rows else None


def draw_icon(f: Frame, name: str, x: int, y: int, color: ColorLike, k: int = 1) -> tuple[int, int]:
    """Draw icon `name` with its top-left at (x, y), each pixel a k×k block. Returns its (w, h) in pixels."""
    rows = ICONS.get(name)
    if not rows:
        return 0, 0
    c = to_rgb(color)
    for yy, row in enumerate(rows):
        for xx, ch in enumerate(row):
            if ch == "#":
                f.rect(x + xx * k, y + yy * k, k, k, c)
    return len(rows[0]) * k, len(rows) * k
