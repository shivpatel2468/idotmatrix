"""Write the studio's page themes from the casino's table themes (docs/STUDIO_UI.md § Page themes).

    uv run python scripts/gen_page_themes.py          # rewrite the generated files
    uv run python scripts/gen_page_themes.py --check  # exit 1 if they are stale (tests/test_page_themes.py runs it)

Source: ``src/deskdot/gfx/tables.py`` ``TABLE_THEMES`` → ``gfx/themes.py`` ``screen_tokens()`` (the CSS tokens of each
table in the dark casino and in the light salon). Output:

* ``web/src/lib/pageThemes.gen.ts`` — every theme's id, name, description, swatch colours, browser / Android bar
  colours and its stylesheet (scoped to ``:root[data-page-theme="<id>"]:not([data-cz])``); lib/pageTheme.ts installs
  the one in use and caches it for the plain pages' first paint.
* ``web/src/pageTheme.default.gen.css`` — the default theme (Cyber grid) for a page that has no ``data-page-theme``
  yet: the studio's first visit paints it before any script runs.
* ``src/deskdot/tv/tv-themes.js`` — the TV view's copy (docs/TV_VIEW.md §2): per theme its tokens under the TV's
  names (``--chassis-*``, ``--ink-*``, ``--ember``, ``--gold`` …) in dark and light, and the table's colours for the
  room around the scene (tv.js applyTheme).
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from deskdot.gfx.themes import DEFAULT_THEME, LEGACY, PAGE_THEMES, PageTheme  # noqa: E402

TS = ROOT / "web/src/lib/pageThemes.gen.ts"
CSS = ROOT / "web/src/pageTheme.default.gen.css"
TV = ROOT / "src/deskdot/tv/tv-themes.js"
STAMP = (
    "generated by scripts/gen_page_themes.py from src/deskdot/gfx/tables.py TABLE_THEMES: do not edit by hand"
)

# the accent tokens a subtree that stays dark in light mode (the dark device's bezel, the fly's 3D scenes) keeps
DARK_SUBTREE = (
    "color-ember",
    "color-ember-2",
    "color-ember-deep",
    "color-ember-line",
    "color-on-ember",
    "color-gold",
    "color-gold-2",
    "color-gold-text",
    "ember",
    "ember2",
    "on-ember",
    "rose",
    "tangerine",
    "gold",
)


def _block(sel: str, tok: dict[str, str]) -> str:
    return f"{sel} {{\n" + "".join(f"  --{k}: {v};\n" for k, v in tok.items()) + "}\n"


def selectors(tid: str, default: bool) -> tuple[list[str], list[str]]:
    """The dark and light selectors of a theme; the default also styles a page with no theme attribute yet."""
    roots = [f':root[data-page-theme="{tid}"]:not([data-cz])']
    if default:
        roots.append(":root:not([data-page-theme]):not([data-cz])")
    return roots, [f'{r}[data-theme="light"]' for r in roots]


def css(t: PageTheme, default: bool = False) -> str:
    tok = t.tokens()
    dark, light = selectors(t.id, default)
    sub = ", ".join(f"{r} :is(.theme-dark, .bezel, .fly-wing, .fly-full, .roam-tip)" for r in light)
    return (
        f"/* page theme: {t.name} ({STAMP}) */\n"
        + _block(", ".join(dark), tok["dark"])
        + _block(", ".join(light), tok["light"])
        + _block(sub, {k: tok["dark"][k] for k in DARK_SUBTREE})
    )


def swatch(tok: dict[str, str]) -> dict[str, str]:
    """What the theme pickers draw (a tiny studio) and the browser / Android bars take, per mode."""
    return {
        "c0": tok["color-chassis-0"],
        "c1": tok["color-chassis-1"],
        "c2": tok["color-chassis-2"],
        "line": tok["color-line-2"],
        "accent": tok["color-ember"],
        "metal": tok["color-gold"],
        "glass": tok["m-glass"],
        "texture": tok["m-texture"],
        "textureSize": tok["m-texture-size"],
    }


def ts() -> str:
    rows = []
    for t in PAGE_THEMES.values():
        tok = t.tokens()
        rows.append(
            {
                "id": t.id,
                "name": t.name,
                "description": t.description,
                "felt": t.table.css["felt"],
                "dark": swatch(tok["dark"]),
                "light": swatch(tok["light"]),
                "css": css(t),
            }
        )
    return (
        f"// {STAMP}\n"
        "// The studio's page themes: the casino's table themes (docs/STUDIO_UI.md § Page themes; lib/pageTheme.ts).\n"
        "/* eslint-disable */\n"
        "export type PageThemeSwatch = { c0: string; c1: string; c2: string; line: string; accent: string; "
        "metal: string; glass: string; texture: string; textureSize: string };\n"
        "export type PageThemeDef = { id: string; name: string; description: string; felt: string; "
        "dark: PageThemeSwatch; light: PageThemeSwatch; css: string };\n"
        f"export const DEFAULT_PAGE_THEME = {json.dumps(DEFAULT_THEME)};\n"
        "/** Page-theme ids from before 3.9 (the studio's own set) → the nearest table. */\n"
        f"export const LEGACY_PAGE_THEMES: Record<string, string> = {json.dumps(LEGACY)};\n"
        "// prettier-ignore\n"
        f"export const PAGE_THEMES: PageThemeDef[] = {json.dumps(rows, indent=1, ensure_ascii=False)};\n"
    )


def default_css() -> str:
    return css(PAGE_THEMES[DEFAULT_THEME], default=True)


# the TV's token names (tv.html :root) ← the studio's
TV_TOKENS = {
    **{f"chassis-{i}": f"color-chassis-{i}" for i in range(5)},
    "line": "color-line",
    "line-2": "color-line-2",
    **{f"ink-{i}": f"color-ink-{i}" for i in range(1, 5)},
    "ember": "color-ember",
    "ember-2": "color-ember-2",
    "on-ember": "color-on-ember",
    "gold": "color-gold",
    "gold-text": "color-gold-text",
    "pink": "color-ember",
}
# the table's colours the TV's room uses (tv.js applyTheme, the same keys as status.table_theme.css)
TV_TABLE = ("felt", "felt2", "felt3", "accent", "accent_hi", "accent_lo", "accent_deep", "accent_rgb", "ink",
            "wing", "wing2", "wing3", "pattern", "pattern_size")  # fmt: skip


def _rgb_of(h: str) -> str:
    x = h.lstrip("#")
    return ", ".join(str(int(x[i : i + 2], 16)) for i in (0, 2, 4))


def tv_js() -> str:
    themes = {}
    for t in PAGE_THEMES.values():
        tok = t.tokens()
        modes = {}
        for mode in ("dark", "light"):
            v = {f"--{k}": tok[mode][src] for k, src in TV_TOKENS.items()}
            v["--ember-rgb"] = _rgb_of(tok[mode]["color-ember"])
            modes[mode] = v
        themes[t.id] = {"name": t.name, **modes, "table": {k: t.table.css[k] for k in TV_TABLE}}
    data = {"default": DEFAULT_THEME, "legacy": LEGACY, "themes": themes}
    return (
        f"/* {STAMP} */\n"
        "/* The TV view's page themes (docs/TV_VIEW.md §2): the casino's table themes, as the studio wears them. */\n"
        f"self.DeskDotTVThemes = {json.dumps(data, indent=1, ensure_ascii=False)};\n"
    )


def outputs() -> dict[Path, str]:
    return {TS: ts(), CSS: default_css(), TV: tv_js()}


def main() -> int:
    check = "--check" in sys.argv
    stale = []
    for path, text in outputs().items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not check:
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print(
            "stale:", ", ".join(str(p.relative_to(ROOT)) for p in stale), "— run scripts/gen_page_themes.py"
        )
        return 1
    print("page themes:", "up to date" if not stale else f"wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
