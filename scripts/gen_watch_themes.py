"""Write the watch's themes from the casino's table themes (docs/DESIGN_TASTE.md §1, §5 "Watch app").

    uv run python scripts/gen_watch_themes.py          # rewrite the generated file
    uv run python scripts/gen_watch_themes.py --check  # exit 1 if it is stale (tests/test_watch_themes.py runs it)

    # another app's copy (Orbit and the watch faces in the gen6-watch repo), same source, its own package:
    uv run python scripts/gen_watch_themes.py --out <file.kt> --package com.gen6.theme [--check]

Source: ``src/deskdot/gfx/tables.py`` ``TABLE_THEMES`` → ``gfx/themes.py`` ``PAGE_THEMES`` ``tokens()``, the same
tokens scripts/gen_page_themes.py writes for the studio, the phone and the TV. Output:

* ``android/wear/src/main/java/com/deskdot/wear/theme/WatchThemes.gen.kt``: every table's id, name, description,
  felt colour and its dark and light palettes as ARGB ints (``android.graphics.Color`` / Compose ``Color(Int)``),
  plus the gold-leaf gradient stops for rims. Plain Kotlin with no Android or Compose imports, so Canvas watch faces,
  Compose apps, Tiles and Complications all read the same file.

The watch draws on OLED black (DESIGN_TASTE §5): the table's accent and felt tone go on rims, rings, tiles and the
glass edge, never as a full-screen fill. The palette carries the whole token set; the apps choose where it goes.
"""

from __future__ import annotations

import re
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from deskdot.gfx.themes import DEFAULT_THEME, LEGACY, PAGE_THEMES  # noqa: E402

KT = ROOT / "android/wear/src/main/java/com/deskdot/wear/theme/WatchThemes.gen.kt"
PACKAGE = "com.deskdot.wear.theme"
STAMP = "generated by scripts/gen_watch_themes.py from src/deskdot/gfx/tables.py TABLE_THEMES: do not edit by hand"

# Kotlin property ← studio token (the same names gen_page_themes.py writes as CSS variables)
PALETTE = {
    **{f"chassis{i}": f"color-chassis-{i}" for i in range(5)},
    "line": "color-line",
    "line2": "color-line-2",
    **{f"ink{i}": f"color-ink-{i}" for i in range(1, 5)},
    "accent": "color-ember",
    "accent2": "color-ember-2",
    "accentDeep": "color-ember-deep",
    "accentLine": "color-ember-line",
    "onAccent": "color-on-ember",
    "metal": "color-gold",
    "metal2": "color-gold-2",
    "metalText": "color-gold-text",
    "glass": "m-glass",
    "glassLine": "m-glass-line",
    "glassEdge": "lg-edge",
    "glassEdgeStrong": "lg-edge-strong",
    "glassRim": "lg-rim-a",
    "keyFloor": "m-key-floor",
    "champagne": "m-champagne",
    "felt": "pt-felt",
    "wing": "pt-wing",
    "wing2": "pt-wing-2",
    "wing3": "pt-wing-3",
}

_HEX = re.compile(r"#([0-9a-fA-F]{3}|[0-9a-fA-F]{6}|[0-9a-fA-F]{8})")
_RGBA = re.compile(r"rgba?\(\s*([\d.]+)\s*,\s*([\d.]+)\s*,\s*([\d.]+)\s*(?:,\s*([\d.]+%?)\s*)?\)")
_STOP = re.compile(r"(#[0-9a-fA-F]{3,8}|rgba?\([^)]*\))\s+([\d.]+)%")


def argb(css: str) -> int:
    """A CSS colour (#rgb, #rrggbb, #rrggbbaa, rgb(), rgba()) as an ARGB int; anything else is an error, so a table
    that changes a watch token to a gradient fails here instead of drawing the wrong thing on the watch."""
    s = css.strip()
    if m := _HEX.fullmatch(s):
        h = m.group(1)
        if len(h) == 3:
            h = "".join(c * 2 for c in h)
        a = int(h[6:8], 16) if len(h) == 8 else 255
        r, g, b = (int(h[i : i + 2], 16) for i in (0, 2, 4))
    elif m := _RGBA.fullmatch(s):
        r, g, b = (round(float(m.group(i))) for i in (1, 2, 3))
        al = m.group(4)
        if al is None:
            a = 255
        elif al.endswith("%"):
            a = round(float(al[:-1]) * 255 / 100)
        else:
            a = round(float(al) * 255)
    else:
        raise ValueError(f"not a plain colour: {css!r}")
    return (a << 24) | (r << 16) | (g << 8) | b


def gradient_stops(css: str) -> list[tuple[float, int]]:
    """The colour stops of a linear-gradient with explicit percentages (the gold leaf)."""
    stops = [(float(pos) / 100, argb(col)) for col, pos in _STOP.findall(css)]
    if len(stops) < 2:
        raise ValueError(f"no colour stops in {css!r}")
    return stops


def _int(v: int) -> str:
    return f"0x{v:08X}.toInt()"


def _str(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"').replace("$", "\\$") + '"'


def _palette(tok: dict[str, str]) -> str:
    args = ", ".join(f"{k} = {_int(argb(tok[src]))}" for k, src in PALETTE.items())
    stops = gradient_stops(tok["m-gold-leaf"])
    pos = ", ".join(f"{p:g}f" for p, _ in stops)
    cols = ", ".join(_int(c) for _, c in stops)
    return f"WatchPalette({args}, goldLeafColors = intArrayOf({cols}), goldLeafStops = floatArrayOf({pos}))"


def kt(package: str = PACKAGE) -> str:
    fields = "".join(f"    val {k}: Int,\n" for k in PALETTE)
    rows = []
    for t in PAGE_THEMES.values():
        tok = t.tokens()
        rows.append(
            f"        WatchTheme(\n"
            f"            id = {_str(t.id)},\n"
            f"            name = {_str(t.name)},\n"
            f"            description = {_str(t.description)},\n"
            f"            felt = {_int(argb(t.table.css['felt']))},\n"
            f"            dark = {_palette(tok['dark'])},\n"
            f"            light = {_palette(tok['light'])},\n"
            f"        ),\n"
        )
    legacy = ", ".join(f"{_str(k)} to {_str(v)}" for k, v in LEGACY.items())
    return (
        f"// {STAMP}\n"
        "// The watch's themes: the casino's table themes (docs/DESIGN_TASTE.md §1, §5). Colours are ARGB ints.\n"
        '@file:Suppress("MaxLineLength")\n\n'
        f"package {package}\n\n"
        "/** One mode (dark or light) of a table theme, under the studio's token names (see the generator). */\n"
        "class WatchPalette(\n"
        f"{fields}"
        "    /** The gold-leaf gradient (`m-gold-leaf`): colours and their positions 0..1, for rims and the LED logo plate. */\n"
        "    val goldLeafColors: IntArray,\n"
        "    val goldLeafStops: FloatArray,\n"
        ")\n\n"
        "/** A casino table theme: the same id and name as the phone, the studio, the TV and the website. */\n"
        "class WatchTheme(\n"
        "    val id: String,\n"
        "    val name: String,\n"
        "    val description: String,\n"
        "    val felt: Int,\n"
        "    val dark: WatchPalette,\n"
        "    val light: WatchPalette,\n"
        ") {\n"
        "    fun palette(dark: Boolean): WatchPalette = if (dark) this.dark else light\n"
        "}\n\n"
        "object WatchThemes {\n"
        f"    const val DEFAULT: String = {_str(DEFAULT_THEME)}\n\n"
        "    /** Theme ids from before 3.9 → the nearest table (the same map as the studio). */\n"
        f"    val LEGACY: Map<String, String> = mapOf({legacy})\n\n"
        "    /** All tables, in the studio's order. */\n"
        "    val ALL: List<WatchTheme> = listOf(\n"
        f"{''.join(rows)}"
        "    )\n\n"
        "    private val byId: Map<String, WatchTheme> = ALL.associateBy { it.id }\n\n"
        "    /** The table for [id] (old ids mapped), or the default when it's unknown. */\n"
        "    fun get(id: String?): WatchTheme =\n"
        "        byId[id] ?: byId[LEGACY[id]] ?: byId.getValue(DEFAULT)\n"
        "}\n"
    )


def outputs(out: Path = KT, package: str = PACKAGE) -> dict[Path, str]:
    return {out: kt(package)}


def main(argv: list[str]) -> int:
    check = "--check" in argv
    out, package = KT, PACKAGE
    if "--out" in argv:
        out = Path(argv[argv.index("--out") + 1]).resolve()
    if "--package" in argv:
        package = argv[argv.index("--package") + 1]
    stale = []
    for path, text in outputs(out, package).items():
        old = path.read_text(encoding="utf-8") if path.exists() else None
        if old != text:
            stale.append(path)
            if not check:
                path.parent.mkdir(parents=True, exist_ok=True)
                path.write_text(text, encoding="utf-8", newline="\n")
    if check and stale:
        print("stale:", ", ".join(str(p) for p in stale), "— run scripts/gen_watch_themes.py")
        return 1
    print("watch themes:", "up to date" if not stale else f"wrote {len(stale)} file(s)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
